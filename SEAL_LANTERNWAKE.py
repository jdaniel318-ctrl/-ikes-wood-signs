"""Version-neutral final-byte wrapper, preserving the historical inherited sealer.
Usage: python SEAL_LANTERNWAKE.py RELEASE_DIR --baseline EXACT_BASELINE [--dry-run]
Finish source, compilation, embedded host digest, current reports and evidence first.
All generated bytes are staged and checked before writing the five final metadata
files. Historical evidence and source files are never rewritten. No authenticity,
service access, native acceptance or live authority is established by these hashes.
"""
from __future__ import annotations
import argparse,json,sys,tempfile
from pathlib import Path
from SEAL_BLACKTIDE import encoded,seal_release
from VERIFY_PACKAGE import CONTENT_DIGEST_ALGORITHM,LEDGERS,PackageError,content_digest,parse_json,require,sha,verify_full


def finalize_release(root: Path, baseline: Path, *, dry_run: bool = False):
    root=Path(root);baseline=Path(baseline)
    entries=[p for p in root.iterdir() if p.name not in ('.git','__pycache__')]
    require(not any(p.is_symlink() or p.is_dir() for p in entries),'Release must contain regular flat files only')
    data={p.name:p.read_bytes() for p in entries}
    m=parse_json(data,'DEPLOYMENT_MANIFEST.json');contract=parse_json(data,'PATCH_CONTRACT.json')
    require(contract.get('target_build')==m.get('build') and contract.get('target_seal')==m.get('release_seal'),'Patch target identity mismatch')
    require(contract.get('requires_deletions') is False and contract.get('database_actions')=='none','Unsupported deletion/database contract')
    inv=json.loads((baseline/'RELEASE_INVENTORY.json').read_bytes())
    original={n:(baseline/n).read_bytes() for n in inv['files']}
    previous=verify_full(original,historical=True)
    require(any(b.get('build')==previous['build'] and b.get('content_digest_algorithm')==CONTENT_DIGEST_ALGORITHM and b.get('content_sha256')==content_digest(original) for b in contract.get('supported_bases',[])),'Baseline content is not supported by current patch contract')
    require(set(original)<=set(data),'Release omits an existing baseline file')
    for name,entry in m.get('lazy_program_assets',{}).items():
        require(name in data,'Missing compiled asset: '+name)
        digest=sha(data[name]);entry['sha256']=digest;entry['bytes']=len(data[name])
        if name=='stormwake_player.html':
            require(len(data[name])<1048576,'Compiled player exceeds existing size limit')
            require(digest.encode() in data.get('fun_program.js',b''),'Compile and update the host player digest before finalization')
    data['DEPLOYMENT_MANIFEST.json']=encoded(m)
    generated=('DEPLOYMENT_MANIFEST.json','RELEASE_INVENTORY.json',*LEDGERS)
    with tempfile.TemporaryDirectory(prefix='release-finalize-') as td:
        staged=Path(td)
        for name,body in data.items():(staged/name).write_bytes(body)
        result=seal_release(staged,baseline)
        final={n:(staged/n).read_bytes() for n in data}
        changed=[n for n in final if original.get(n)!=final[n]]
        limit=min(85,int(contract.get('max_upload_files',85)))
        require(0<len(changed)<=limit,f'Final update exceeds {limit}-file upload budget')
        if not dry_run:
            for name in generated:(root/name).write_bytes(final[name])
    return {'pass':True,**result,'changed_files':len(changed),'dry_run':dry_run,'scope':'final metadata byte agreement only; archive/extraction/browser/native checks remain separate'}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('release',type=Path);p.add_argument('--baseline',type=Path,required=True);p.add_argument('--dry-run',action='store_true');args=p.parse_args()
    try:print(json.dumps(finalize_release(args.release,args.baseline,dry_run=args.dry_run),indent=2));return 0
    except (PackageError,OSError,KeyError,TypeError,ValueError) as exc:print(json.dumps({'pass':False,'error':str(exc)},indent=2));return 1
if __name__=='__main__':sys.exit(main())
