'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, 'fleet_help.js');
assert.ok(fs.existsSync(file), 'The shared fleet-help component must exist');
const {listMethod, validReply, nextActions, errorMessage} = require(file);
assert.equal(listMethod('owner'), 'owner_list_fleet_help');
assert.equal(listMethod('captain'), 'vessel_captain_list_fleet_help');
assert.equal(listMethod('admiral'), 'admiral_list_fleet_help');
assert.throws(() => listMethod('unknown'));
const pending = {project_id:'lp',request_id:'test',version:1,status:'open'};
assert.ok(validReply(pending, 'lp', 'test'));
assert.equal(validReply({...pending,project_id:'other'}, 'lp', 'test'), false);
assert.equal(validReply({...pending,status:'bad'}, 'lp', 'test'), false);
assert.equal(validReply({...pending,request_id:'other'}, 'lp', 'test'), false);
assert.equal(validReply({...pending,version:0}, 'lp', 'test'), false);
assert.deepEqual(nextActions('owner','open'), []);
assert.deepEqual(nextActions('admiral','in_progress'), []);
assert.deepEqual(nextActions('captain','open'), ['in_progress']);
assert.deepEqual(nextActions('captain','in_progress'), ['verified']);
assert.deepEqual(nextActions('captain','verified'), []);
assert.match(errorMessage({code:'PGRST202'}), /setup/i);
assert.match(errorMessage({code:'42501'}), /access/i);
assert.match(errorMessage({status:403}), /access/i);
console.log('PASS Signalman role routes, scoped receipts, workflow and error states');
